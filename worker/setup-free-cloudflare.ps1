$ErrorActionPreference = "Stop"
$WorkerDir = $PSScriptRoot
$RepoRoot = Split-Path $WorkerDir -Parent
$DbName = "nekitosha-mlbot"

function Run-Wrangler {
    param([string[]]$Arguments)
    & wrangler @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Wrangler command failed: wrangler $($Arguments -join ' ')" }
}

try {
    Write-Host ""
    Write-Host "NEKITOSHA AUTOFARM - FREE CLOUDFLARE SETUP" -ForegroundColor Cyan
    Write-Host "This creates a D1 database, applies the schema and deploys the API."
    Write-Host ""

    if (-not (Get-Command npm -ErrorAction SilentlyContinue)) {
        throw "Node.js/npm not found. Install Node.js LTS from https://nodejs.org/ and run this script again."
    }
    if (-not (Get-Command wrangler -ErrorAction SilentlyContinue)) {
        Write-Host "Installing Wrangler..."
        & npm install --global wrangler
        if ($LASTEXITCODE -ne 0) { throw "Could not install Wrangler." }
    }

    Push-Location $WorkerDir
    try {
        Write-Host "Opening Cloudflare login..."
        Run-Wrangler @("login")

        $configPath = Join-Path $WorkerDir "wrangler.toml"
        $config = Get-Content -LiteralPath $configPath -Raw -Encoding UTF8

        Write-Host "Checking D1 database..."
        $listText = (& wrangler d1 list --json 2>&1 | Out-String)
        if ($LASTEXITCODE -ne 0) { throw "Could not list D1 databases: $listText" }
        $list = $listText | ConvertFrom-Json
        if ($list.result) { $items = @($list.result) } else { $items = @($list) }
        $db = $items | Where-Object { $_.name -eq $DbName -or $_.database_name -eq $DbName } | Select-Object -First 1
        $databaseId = $null
        if ($db) {
            if ($db.uuid) { $databaseId = $db.uuid }
            elseif ($db.database_id) { $databaseId = $db.database_id }
        }

        if (-not $databaseId) {
            Write-Host "Creating D1 database..."
            $createText = (& wrangler d1 create $DbName --binding DB 2>&1 | Out-String)
            if ($LASTEXITCODE -ne 0) {
                throw "D1 database creation failed. Check Cloudflare for an existing database named $DbName. Details: $createText"
            }
            $match = [regex]::Match($createText, 'database_id\s*=\s*"([0-9a-fA-F-]{20,})"')
            if ($match.Success) { $databaseId = $match.Groups[1].Value }
            if (-not $databaseId) {
                $listText = (& wrangler d1 list --json 2>&1 | Out-String)
                $list = $listText | ConvertFrom-Json
                if ($list.result) { $items = @($list.result) } else { $items = @($list) }
                $db = $items | Where-Object { $_.name -eq $DbName -or $_.database_name -eq $DbName } | Select-Object -First 1
                if ($db.uuid) { $databaseId = $db.uuid }
                elseif ($db.database_id) { $databaseId = $db.database_id }
            }
        }
        if (-not $databaseId) { throw "Could not determine D1 database ID. Run wrangler d1 list and copy the UUID into worker/wrangler.toml." }

        $config = [regex]::Replace($config, 'database_id\s*=\s*"[^"]+"', ('database_id = "' + $databaseId + '"'), 1)
        [IO.File]::WriteAllText($configPath, $config, (New-Object System.Text.UTF8Encoding($false)))

        Write-Host "Applying database schema..."
        Run-Wrangler @("d1","execute",$DbName,"--remote","--file=./schema.sql")

        Write-Host "Deploying API Worker..."
        $deployText = (& wrangler deploy 2>&1 | Out-String)
        if ($LASTEXITCODE -ne 0) { throw "Worker deployment failed: $deployText" }
        Write-Host $deployText
        $urlMatch = [regex]::Match($deployText, 'https://[a-zA-Z0-9.-]+\.workers\.dev')
        if (-not $urlMatch.Success) { throw "Worker deployed, but its URL was not detected. Copy the workers.dev URL into web/config.js as API_BASE." }
        $workerUrl = $urlMatch.Value.TrimEnd('/')

        $webConfig = Join-Path $RepoRoot "web\config.js"
        $nl = [Environment]::NewLine
        $configJs = "// Generated by setup-free-cloudflare.ps1" + $nl + 'window.MLBOT_CONFIG = { API_BASE: "' + $workerUrl + '" };' + $nl
        [IO.File]::WriteAllText($webConfig, $configJs, (New-Object System.Text.UTF8Encoding($false)))

        Write-Host ""
        Write-Host "API deployed: $workerUrl" -ForegroundColor Green
        Write-Host "Frontend config updated: web/config.js" -ForegroundColor Green

        if ((Get-Command git -ErrorAction SilentlyContinue) -and (Test-Path (Join-Path $RepoRoot ".git"))) {
            $answer = Read-Host "Commit and push Worker configuration to GitHub now? (Y/N)"
            if ($answer -match '^[Yy]$') {
                Push-Location $RepoRoot
                try {
                    & git add "worker/wrangler.toml" "web/config.js"
                    & git commit -m "Configure Cloudflare AutoFarm API"
                    if ($LASTEXITCODE -eq 0) {
                        & git push
                        if ($LASTEXITCODE -ne 0) { Write-Host "Push failed. Run git push manually." -ForegroundColor Yellow }
                    } else {
                        Write-Host "No new files to commit, or commit failed. Check git status." -ForegroundColor Yellow
                    }
                } finally { Pop-Location }
            } else {
                Write-Host "Commit worker/wrangler.toml and web/config.js to GitHub when ready." -ForegroundColor Yellow
            }
        } else {
            Write-Host "This folder is not a Git clone. Upload worker/wrangler.toml and web/config.js to GitHub using GitHub Desktop or the website." -ForegroundColor Yellow
        }
    } finally { Pop-Location }

    Write-Host ""
    Write-Host "CLOUDFLARE SETUP FINISHED." -ForegroundColor Green
}
catch {
    Write-Host ""
    Write-Host ("SETUP ERROR: " + $_.Exception.Message) -ForegroundColor Red
}
finally {
    Write-Host ""
    Read-Host "Press Enter to close"
}
